public class basicqustion {

    public static void main(String[] args) {
        // sum
        int x = 10;
        int y = 15;
        int sum = x + y;
        System.out.println(sum);

        // product
        int a = 10;
        int b = 15;
        int prod = a * b;
        System.out.println(prod);

        // divided

        int c = 10;
        int d = 15;

        int d1 = c / d;
        int d2 = d / c;
        int d3 = c % d;

        System.out.println(d1);
        System.out.println(d2);
        System.out.println(d3);

        // exp

        int exp = x * y / x + y;
        System.out.println(exp);

    }
}